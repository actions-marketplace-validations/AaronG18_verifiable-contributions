"""Render a receipt as a short, human-readable review note."""

from __future__ import annotations

from .receipt import VERDICT_VERIFIED, Receipt

_VERDICT_LABEL = {
    "VERIFIED": "Verified",
    "NEEDS_EVIDENCE": "Needs evidence",
    "NEEDS_RERUN": "Needs rerun",
    "UNTRUSTED": "Untrusted verifier change",
}


def _sanitize(value: str) -> str:
    """Render PR-author-controlled text inert inside the job summary.

    Test output is untrusted: it can contain closing code fences, Markdown
    headings or raw HTML. Escape them so a crafted failure cannot forge a
    "Verified" section or inject markup into $GITHUB_STEP_SUMMARY.
    """
    escaped = (
        value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("`", "&#96;")
    )
    # Defence in depth: even if a future renderer changes how fences work, a
    # line from test output must never become a Markdown heading or quote.
    lines = []
    for line in escaped.split("\n"):
        stripped = line.lstrip()
        if stripped.startswith(("#", ">", "|")):
            marker = stripped[0]
            line = line[: len(line) - len(stripped)] + f"&#{ord(marker)};" + stripped[1:]
        lines.append(line)
    return "\n".join(lines)


def render_markdown(receipt: Receipt) -> str:
    r = receipt
    label = _VERDICT_LABEL.get(r.verdict, r.verdict)
    lines = [
        f"## Verification receipt: {label}",
        "",
        _sanitize(r.reason),
        "",
        "| | Base | Head |",
        "| --- | --- | --- |",
        f"| Commit | `{r.base_sha[:12]}` | `{r.head_sha[:12]}` |",
        f"| Exit code | `{r.base_run.exit_code}` | `{r.head_run.exit_code}` |",
        f"| stdout sha256 | `{r.base_run.stdout_sha256[:16]}...` | "
        f"`{r.head_run.stdout_sha256[:16]}...` |",
        f"| stderr sha256 | `{r.base_run.stderr_sha256[:16]}...` | "
        f"`{r.head_run.stderr_sha256[:16]}...` |",
        f"| Duration | {r.base_run.duration_seconds:.1f}s | {r.head_run.duration_seconds:.1f}s |",
        f"| Failure kind | `{r.base_run.failure_kind}` | `{r.head_run.failure_kind}` |",
        "",
        f"Command: `{' '.join(r.command)}`",
        "",
        f"Test files replayed: {len(r.test_files_sha256)}. "
        "The head's test paths were copied onto the base tree; the source change was not.",
        "",
        f"Verifier: `vrc {r.environment.get('verifier_version', '?')}` on "
        f"Python {r.environment.get('python', '?')} ({r.environment.get('platform', '?')}).",
    ]
    if r.verdict == VERDICT_VERIFIED:
        lines += [
            "",
            "The base failure was classified as an assertion failure, so the tests "
            "fail without the change and pass with it in this CI environment. This "
            "does not prove the change is correct, only that the claimed behaviour "
            "is exercised by a test. A human still reviews.",
            "",
            f"Base failure evidence: `{_sanitize(r.base_run.failure_evidence[:300])}`",
        ]
    elif r.base_run.failure_kind == "environment":
        lines += [
            "",
            f"Base failure evidence: `{_sanitize(r.base_run.failure_evidence[:300])}`",
        ]
    if r.base_run.stderr_excerpt and r.verdict != VERDICT_VERIFIED:
        lines += [
            "",
            "<details><summary>Base run stderr (last lines)</summary>",
            "",
            "```",
            _sanitize(r.base_run.stderr_excerpt[-800:]),
            "```",
            "",
            "</details>",
        ]
    if r.head_run.stderr_excerpt and r.verdict != VERDICT_VERIFIED:
        lines += [
            "",
            "<details><summary>Head run stderr (last lines)</summary>",
            "",
            "```",
            _sanitize(r.head_run.stderr_excerpt[-800:]),
            "```",
            "",
            "</details>",
        ]
    lines += [
        "",
        "Generated by the maintainer's CI. Re-run with `vrc replay` to reproduce; "
        "validate integrity with `vrc check receipt.json`.",
    ]
    return "\n".join(lines) + "\n"
